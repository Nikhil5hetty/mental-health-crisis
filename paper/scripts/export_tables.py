def word_models() -> None:
    from experiments.rq2.run_rq2 import WEIGHT_WORDS
    from src.cww import APPROPRIATENESS_WORDS, appropriateness_codebook  # noqa: F401
    from src.cww.rules import CRISIS_WORDS
    w = 0.25  # default fou_width of appropriateness_codebook (src/cww/codebook.py)
    p = lambda t: '(' + ', '.join(f'{v:g}' for v in t) + ')'  # noqa: E731
    import numpy as np
    from src.cww import it2_trapezoid
    book = appropriateness_codebook(w)
    rows = []
    for k, word in enumerate(APPROPRIATENESS_WORDS, 1):
        umf = (k - 0.75 - w / 2, k - 0.25, k + 0.25, k + 0.75 + w / 2)
        lmf = (k - 0.75 + w / 2, k - 0.25, k + 0.25, k + 0.75 - w / 2)
        ref, mine = book.sets[k - 1], it2_trapezoid(umf, lmf)
        if not (np.allclose(ref.umf, mine.umf) and np.allclose(ref.lmf, mine.lmf)):  # table must match the code
            raise ValueError(f'Word-model table differs from appropriateness_codebook for {word}')
        rows.append(['Reply appropriateness', word, p(umf), p(lmf)])
    rows.append(['MIDRULE'])
    for word, (umf, lmf) in WEIGHT_WORDS.items():
        rows.append(['Judge reliability (LWA weight)', word, p(umf), p(lmf)])
    rows.append(['MIDRULE'])
    for word, t in CRISIS_WORDS.items():
        rows.append(['Crisis level (T1)', word, p(t), '= UMF'])
    write('word_models', tabular('llll', ['Vocabulary', 'Word', 'UMF $(a,b,c,d)$', 'LMF $(a,b,c,d)$'], rows))


def rule_table() -> None:
    from src.cww import APPROPRIATENESS_WORDS
    from src.cww.rules import CRISIS_WORDS, RULE_TABLE
    short = [w.split()[0].split('/')[0] for w in APPROPRIATENESS_WORDS]
    rows = [[c] + [f'A{RULE_TABLE[(c, r)]}' for r in APPROPRIATENESS_WORDS] for c in CRISIS_WORDS]
    write('rule_table', tabular('l' + 'c' * len(short), ['Crisis level $\\backslash$ reply word'] + short, rows,
                                small=False))


def rq1_calibration() -> None:
    rows = []
    for lv in ['0', '0.25', '0.5', '0.75', '1']:
        st = f'mu_H={lv}'
        rows.append([lv, est('rq1', 'N_items', 'all', st), full('rq1', 'mean_mu_L', 'all', st)])
    write('rq1_calibration', tabular('crl', [r'$\mu_H$', 'Items', r'Mean $\mu_L$ [95\% CI]'], rows, small=False))


SYSTEM_LABELS = {'S1_gpt-4o-mini': 'S1 gpt-4o-mini', 'S1_gpt-5-nano': 'S1 gpt-5-nano',
                 'S1_meta-llama': 'S1 meta-llama', 'S2': 'S2 crisp jury', 'S3': 'S3 fuzzy panel',
                 'S4': 'S4 OWA', 'S5': 'S5 LWA'}


def rq2_main() -> None:
    rows = []
    for s, label in SYSTEM_LABELS.items():
        cells = [('rq2', 'M1_exact', s), ('rq2', 'M1_qwk', s), ('rq2', 'M2_jaccard', s), ('rq2', 'M3_recall', s),
                 ('rq2', 'M3_precision', s)]
        r = est_ci_rows(label, cells)
        if s.startswith('S1_'):
            r[0].append('--'), r[1].append('')
        else:
            r[0].append(est('rq2', 'M4a_flip_rate', s)), r[1].append(r'{\scriptsize ' + ci('rq2', 'M4a_flip_rate', s) + '}')
        r[0].append(est('rq2', 'M4b_flip_rate', s)), r[1].append(r'{\scriptsize ' + ci('rq2', 'M4b_flip_rate', s) + '}')
        rows += r
    write('rq2_main', tabular('lccccccc', ['System', 'M1 exact', 'M1 QWK', 'M2 Jaccard', 'M3 recall', 'M3 precision',
                                           'M4a flip', 'M4b flip'], rows))


def rq2_uncertainty() -> None:
    rows = []
    for u, label in [('S2[run_std]', 'S2: std of all runs'), ('S3[1-maxJ]', r'S3: $1-\max J$'),
                     ('S3[width]', 'S3: centroid width'), ('S5[1-maxJ]', r'S5: $1-\max J$'),
                     ('S5[width]', 'S5: centroid width')]:
        rows.append([label, full('rq2', 'M5_rho_disagreement', u), full('rq2', 'M5_rho_abs_error', u)])
    write('rq2_uncertainty', tabular('lll', ['Uncertainty measure', r'$\rho$ with human disagreement',
                                             r'$\rho$ with absolute error'], rows, small=False))


def recorded_verdicts(part: str) -> list[tuple[str, str]]:
    """(hypothesis id, verdict) in table order from results/<part>/SUMMARY.md."""
    out = []
    for line in (ROOT / f'results/{part}/SUMMARY.md').read_text(encoding='utf-8').splitlines():
        m = re.match(r'\| (H\d[a-c]?) \|', line)
        if m:
            verdict = line.rstrip(' |').rsplit('|', 1)[1].strip()
            out.append((m.group(1), verdict.split(' (')[0]))
    return out


def hypotheses() -> None:
    spec = [  # (part, id, statement, [(metric, group, stratum, label)])
        ('rq1', 'H1a', r'Spearman $\rho(\mu_H,\mu_L)>0$ on human-split items',
         [('spearman_mu_H_mu_L', 'all', 'human_split', r'$\rho$')]),
        ('rq1', 'H1b', 'Crisp disagreement higher on split than unanimous items',
         [('DIFF_crisp_disagreement_rate', 'human_split-unanimous', 'overall', 'difference')]),
        ('rq2', 'H2a', r'S3 (M3) recall $\geq$ S2, precision $\geq$ S2 $-0.10$',
         [('DIFF_M3_recall', 'S3-S2', 'overall', 'recall'), ('DIFF_M3_precision', 'S3-S2', 'overall', 'precision')]),
        ('rq2', 'H2a', r'S3 (M3b) recall $\geq$ S2, precision $\geq$ S2 $-0.10$',
         [('DIFF_M3b_vs_M3_recall', 'S3-S2', 'overall', 'recall'),
          ('DIFF_M3b_vs_M3_precision', 'S3-S2', 'overall', 'precision')]),
        ('rq2', 'H2a', r'S5 (M3) recall $\geq$ S2, precision $\geq$ S2 $-0.10$',
         [('DIFF_M3_recall', 'S5-S2', 'overall', 'recall'), ('DIFF_M3_precision', 'S5-S2', 'overall', 'precision')]),
        ('rq2', 'H2a', r'S5 (M3b) recall $\geq$ S2, precision $\geq$ S2 $-0.10$',
         [('DIFF_M3b_vs_M3_recall', 'S5-S2', 'overall', 'recall'),
          ('DIFF_M3b_vs_M3_precision', 'S5-S2', 'overall', 'precision')]),
        ('rq2', 'H2b', r'S3 drop-one flip rate $\leq$ S2', [('DIFF_M4a_flip_rate', 'S3-S2', 'overall', 'difference')]),
        ('rq2', 'H2b', r'S5 drop-one flip rate $\leq$ S2', [('DIFF_M4a_flip_rate', 'S5-S2', 'overall', 'difference')]),
        *[('rq2', 'H2c', rf'{s} {lab} tracks disagreement more than S2 run std',
           [('DIFF_M5_rho_disagreement', f'{s}[{u}]-S2[run_std]', 'overall', r'$\Delta\rho$')])
          for s in ['S3', 'S5'] for u, lab in [('1-maxJ', r'$1-\max J$'), ('width', 'width')]],
        ('demo', 'H3', r'P-fuzzy under-escalation (oracle A2/A3) $\leq$ P-crisp',
         [('DIFF_under_escalation_rate', 'P-fuzzy-P-crisp', 'oracle_A2_A3', 'difference')]),
    ]
    verdicts = {p: recorded_verdicts(p) for p in ['rq1', 'rq2', 'demo']}
    used = {p: 0 for p in verdicts}
    rows = []
    for part, hid, statement, quantities in spec:
        rec_id, verdict = verdicts[part][used[part]]
        used[part] += 1
        if rec_id != hid:
            raise ValueError(f'Order mismatch with {part} SUMMARY: expected {hid}, found {rec_id}')
        evidence = '; '.join(f'{lab} {full(part, m, g, st)}' for m, g, st, lab in quantities)
        rows.append([hid, statement, evidence, verdict])
    for p, n in used.items():
        if n != len(verdicts[p]):
            raise ValueError(f'{p}: {len(verdicts[p])} recorded hypotheses, {n} exported')
    write('hypotheses', tabular('lp{0.33\\linewidth}p{0.34\\linewidth}l',
                                ['ID', 'Hypothesis (exploratory)', 'Estimate [95\\% CI]', 'Recorded verdict'], rows))


def cb_summary() -> None:
    strata = ['overall', 'gpt4', 'llama3', 'gemini', 'human']
    spec = [('share_split_panel', 'medical_advice', 'Medical advice: split panel (1--4 of 5 ``yes\'\')'),
            ('not_sure_reply_share', 'medical_advice', 'Medical advice: $\\geq$1 ``not sure\'\''),
            ('share_range_ge2', 'overall', 'Overall quality: experts span $\\geq$2 levels'),
            ('share_range_ge2', 'toxicity', 'Toxicity: experts span $\\geq$2 levels'),
            ('share_contested', 'toxicity', 'Toxicity: contested decoded panel'),
            ('share_crisp_word_differs', 'toxicity', 'Toxicity: crisp word $\\neq$ decoded word'),
            ('share_k1_among_flagged', 'medical', 'Medical risk: one copier among flagged')]
    rows = []
    for metric, group, label in spec:
        rows += est_ci_rows(label, [('counselbench', metric, group, s) for s in strata])
    write('cb_summary', tabular('p{0.3\\linewidth}ccccc', ['Quantity (share of replies)', 'All', 'GPT-4', 'LLaMA 3',
                                                         'Gemini', 'Human'], rows))


def demo_tables() -> None:
    rows = []
    for p in ['P-fuzzy', 'P-crisp']:
        rows += est_ci_rows(p, [('demo', 'exact_agreement_with_oracle', p), ('demo', 'qwk_with_oracle', p),
                                ('demo', 'under_escalation_rate', p), ('demo', 'under_escalation_rate', p, 'oracle_A2_A3'),
                                ('demo', 'over_escalation_rate', p)])
    write('demo_agreement', tabular('lccccc', ['Pipeline', 'Exact', 'QWK', 'Under (all)', 'Under (oracle A2/A3)',
                                               'Over (all)'], rows))
    rows = []
    for p in ['P-fuzzy', 'P-crisp', 'Oracle']:
        rows += est_ci_rows(p, [('demo', 'share_action', f'{p}|A{i}') for i in range(4)])
    write('demo_actions', tabular('lcccc', ['Pipeline', 'A0', 'A1', 'A2', 'A3'], rows))


def copy_figures() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    for part in ['rq1', 'rq2', 'counselbench', 'demo']:
        for f in sorted((ROOT / f'results/{part}/figures').glob('*.png')):
            shutil.copyfile(f, FIG / f'{part}_{f.name}')


def main() -> None:
    TAB.mkdir(parents=True, exist_ok=True)
    for fn in [datasets, word_models, rule_table, rq1_calibration, rq2_main, rq2_uncertainty, hypotheses, cb_summary,
               demo_tables]:
        fn()
    copy_figures()
    print(f'Wrote {len(list(TAB.glob("*.tex")))} tables to paper/generated/tables and copied figures to paper/figures')


if __name__ == '__main__':
    main()
