#!/usr/bin/env python3
"""Write the paper's LaTeX tables from results/words/*.csv and copy the figures.

- Numbers come from the committed CSVs, formatted like export_numbers.py (and the SUMMARY.md files).
- Hypothesis verdicts are copied from the recorded results/words/*/SUMMARY.md files; they are never recomputed.
- The rule table and the crisis-level words come from the code that defines them (src/cww/rules.py,
  src/cww/verbalise.py).
- Figures are copied from results/words/*/figures/ to paper/figures/words_<rq>_<name>.png, and the app
  screenshots from docs/img/ to paper/figures/app_<name>.png.

Run from anywhere:  python -I paper/scripts/export_tables.py
"""
from __future__ import annotations

import math
import re
import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from paper.scripts.export_numbers import fmt_int, fmt_num, word_decimals  # noqa: E402

W = ROOT / 'results/words'
TAB = ROOT / 'paper/generated/tables'
FIG = ROOT / 'paper/figures'
HEADER = '% Generated by paper/scripts/export_tables.py from results/words/. Do not edit by hand.\n'


def tex_escape(s: str) -> str:
    return str(s).replace('&', r'\&').replace('%', r'\%').replace('_', r'\_').replace('#', r'\#')


def write(name: str, body: str) -> None:
    (TAB / f'{name}.tex').write_text(HEADER + body, encoding='utf-8')


def tabular(colspec: str, head: list[str], rows: list[list[str]], small=True) -> str:
    lines = [r'\begingroup' + (r'\footnotesize' if small else ''), rf'\begin{{tabular}}{{{colspec}}}', r'\toprule',
             ' & '.join(head) + r' \\', r'\midrule']
    for r in rows:
        lines.append(r'\midrule' if r == ['MIDRULE'] else ' & '.join(r) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\endgroup', '']
    return '\n'.join(lines)


def full(r, decimals=3) -> str:
    if math.isnan(r.estimate):
        return 'n/a'
    return f'{fmt_num(r.estimate, decimals)} [{fmt_num(r.ci_lo, decimals)}, {fmt_num(r.ci_hi, decimals)}]'


# ----------------------------------------------------------------------------- study design

def profile() -> None:
    p = pd.read_csv(W / 'rq1/respondent_profile.csv')
    labels = {'country': 'Country of residence', 'education': 'Education', 'english_background': 'English',
              'age_band': 'Age'}
    rows = []
    for field, label in labels.items():
        g = p[p.field == field]
        if field == 'age_band':  # natural age order; "missing" last
            g = g.sort_values('category', key=lambda c: c.map(lambda v: (v == 'missing', v != 'Under 18', v)))
        cells = [f'{tex_escape(c)} {fmt_num(100 * s, 1)}\\%' for c, s in zip(g.category, g.share)]
        rows.append([label, '; '.join(cells)])
    n = int(p[p.field == 'all'].n.iloc[0])
    write('profile', tabular('lp{0.72\\linewidth}', [f'Field (n = {fmt_int(n)})', 'Share of respondents'], rows))


def elicitation() -> None:
    inv = pd.read_csv(W / 'rq2/invalid.csv')
    digests = pd.read_csv(ROOT / 'data/llm_answers/answers.csv', usecols=['model', 'digest']).groupby('model').digest.first()
    rows = []
    for (model, prompt), g in inv.groupby(['model', 'prompt_id']):
        rows.append([r'\texttt{' + tex_escape(model) + '}', r'\texttt{' + digests[model][:12] + '}', prompt,
                     f'{fmt_int(g.n_valid.sum())} / {fmt_int(g.n_rows.sum())}',
                     fmt_num(g.n_missing.sum() / g.n_rows.sum()), fmt_int(g.n_reasked.sum()),
                     fmt_int(g.n_length.sum()), fmt_int(g.n_superseded.sum()), str(int((g.included == 0).sum()))])
    write('elicitation', tabular('lllrrrrrr', ['Model tag', 'Digest', 'Prompt', 'Valid / asked', 'Invalid rate',
                                                'Re-asked', 'Token cap', 'Superseded', 'Excl.\\ terms'], rows))


def levels_and_rules() -> None:
    from src.cww import APPROPRIATENESS_WORDS
    from src.cww.rules import CRISIS_WORDS, RULE_TABLE
    from src.cww.verbalise import LEVELS
    if list(LEVELS) != list(CRISIS_WORDS):
        raise ValueError('Level words and rule table disagree')
    short = [w.split()[0].split('/')[0] for w in APPROPRIATENESS_WORDS]
    rows = [[c, '\\word{' + LEVELS[c] + '}'] + [f'A{RULE_TABLE[(c, r)]}' for r in APPROPRIATENESS_WORDS] for c in CRISIS_WORDS]
    write('rule_table', tabular('ll' + 'c' * len(short), ['Crisis level', 'CAPphrase word'] + short, rows, small=False))


# ----------------------------------------------------------------------------- results (used in PR B)

def rq1_fou() -> None:
    m = pd.read_csv(W / 'rq1/metrics.csv')
    p = m[m.group == 'pooled'].pivot(index='term', columns='metric', values='value')
    p = p.sort_values(['fou_area'], ascending=False, kind='stable')
    rows = [[tex_escape(t), fmt_num(r.fou_area, 2), f'[{fmt_num(r.centroid_left, 2)}, {fmt_num(r.centroid_right, 2)}]',
             fmt_num(r.centre, 2), f"{r['iqr']:g}", f"{r['median']:g}"] for t, r in p.iterrows()]
    write('rq1_fou', tabular('lrcrrr', ['Term', 'FOU area', 'EKM centroid $[c_l, c_r]$', 'Centre', 'IQR', 'Median'], rows))


def rq2_terms() -> None:
    m = pd.read_csv(W / 'rq2/metrics.csv')
    get = lambda metric, term, model: m[(m.metric == metric) & (m.term == term) & (m.model == model)].iloc[0]  # noqa: E731
    n_models = m[m.metric == 'jaccard_t1'].groupby('term').size()
    terms = sorted(m[m.metric == 'jaccard_it2'].term, key=lambda t: (-get('jaccard_it2', t, 'llm_it2').estimate, t))
    rows = [[tex_escape(t), full(get('jaccard_it2', t, 'llm_it2')),
             full(get('centroid_shift_it2', t, 'llm_it2'), word_decimals('centroid_shift_it2')),
             full(get('width_ratio', t, 'pooled_llm')), str(n_models[t])] for t in terms]
    write('rq2_terms', tabular('lllll', ['Term', 'Jaccard (citizen IT2, LLM IT2)', 'Centre shift (pp)',
                                         'Width ratio (pooled)', 'Models'], rows))


def recorded_verdicts() -> dict:
    """Verdicts as recorded in the SUMMARY.md files: {(hypothesis, prompt, model): verdict}."""
    out = {}
    text = (W / 'rq2/SUMMARY.md').read_text(encoding='utf-8')
    for prompt, block in re.findall(r'### (P\d) \([a-z]+\)\n(.*?)(?=\n### |\n## )', text, flags=re.S):
        out[('H2a', prompt, 'llm_it2')] = re.search(r'Verdict: \*\*([a-z ]+)\*\*', block).group(1)
        for model, verdict in re.findall(r'^\| (\S+) \| \d+ \| [^|]+ \| ([a-z ]+) \|$', block, flags=re.M):
            out[('H2b', prompt, model)] = verdict
    text = (W / 'rq3/SUMMARY.md').read_text(encoding='utf-8')
    out[('H3', 'P1', 'llm_vs_citizen')] = re.search(r'## H3.*?Verdict: \*\*([a-z ]+)\*\*', text, flags=re.S).group(1)
    return out


def hypotheses() -> None:
    v = recorded_verdicts()
    m2 = {'P1': pd.read_csv(W / 'rq2/metrics.csv'), 'P2': pd.read_csv(W / 'rq2/sensitivity.csv')}
    m3 = pd.read_csv(W / 'rq3/metrics.csv')
    rows = []
    for prompt in ['P1', 'P2']:
        d = m2[prompt]
        r = d[d.metric == 'h2a_D'].iloc[0]
        rows.append(['H2a', prompt, 'hedge $-$ extreme mean Jaccard $< 0$', full(r), v[('H2a', prompt, 'llm_it2')]])
        for r in d[d.metric == 'h2b_share'].itertuples():
            label = 'pooled' if r.model == 'pooled_llm' else r'\texttt{' + tex_escape(r.model) + '}'
            rows.append(['H2b', prompt, f'share LLM IQR $<$ citizen IQR $> 0.5$ ({label})', full(r), v[('H2b', prompt, r.model)]])
        rows.append(['MIDRULE'])
    r = m3[(m3.metric == 'action_flip_rate') & (m3.comparison == 'llm_vs_citizen')].iloc[0]
    rows.append(['H3', 'P1', 'action flip rate LLM vs citizen $> 0$', full(r), v[('H3', 'P1', 'llm_vs_citizen')]])
    n_rows = sum(1 for r in rows if r != ['MIDRULE'])
    if n_rows != len(v):
        raise ValueError(f'{len(v)} recorded verdicts, {n_rows} exported')
    write('hypotheses', tabular('llp{0.36\\linewidth}ll', ['ID', 'Prompt', 'Hypothesis (exploratory)',
                                                            'Estimate [95\\% CI]', 'Recorded verdict'], rows))


def rq3_rates() -> None:
    m = pd.read_csv(W / 'rq3/metrics.csv')
    metrics = ['word_disagreement_rate', 'action_flip_rate', 'under_escalation_rate', 'over_escalation_rate']
    rows = []
    for comp in m.comparison.unique():
        label = comp.replace('llm_vs_', 'LLM vs ').replace('|', ' / ').replace('_', ' ')
        rows.append([tex_escape(label)] + [full(m[(m.metric == x) & (m.comparison == comp)].iloc[0]) for x in metrics])
    write('rq3_rates', tabular('lllll', ['Comparison', 'Word disagreement', 'Action flip', 'Under-escalation',
                                         'Over-escalation'], rows))
    f = pd.read_csv(W / 'rq3/flip_matrix.csv')
    f = f[f.comparison == 'llm_vs_citizen'].pivot(index='reference_action', columns='llm_action', values='n')
    rows = [[i] + [fmt_int(f.loc[i, j]) for j in f.columns] for i in f.index]
    write('rq3_flip_matrix', tabular('l' + 'r' * len(f.columns), ['Citizen $\\backslash$ LLM'] + list(f.columns), rows,
                                     small=False))


def copy_figures() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    for part in ['rq1', 'rq2', 'rq3']:
        for f in sorted((W / part / 'figures').glob('*.png')):
            shutil.copyfile(f, FIG / f'words_{part}_{f.name}')
    for f in sorted((ROOT / 'docs/img').glob('word_lab_*.png')):
        shutil.copyfile(f, FIG / f'app_{f.name}')


def main() -> None:
    TAB.mkdir(parents=True, exist_ok=True)
    for fn in [profile, elicitation, levels_and_rules, rq1_fou, rq2_terms, hypotheses, rq3_rates]:
        fn()
    copy_figures()
    print(f'Wrote {len(list(TAB.glob("*.tex")))} tables to paper/generated/tables and copied figures to paper/figures')


if __name__ == '__main__':
    main()
