#!/usr/bin/env python3
"""Write the paper's LaTeX tables from results/*.csv and copy the figures.

- Numbers come from results/*/metrics.csv (formatted like export_numbers.py).
- Hypothesis verdicts are copied from the recorded results/*/SUMMARY.md tables
  (a pre-registered result keeps its recorded verdict); they are never recomputed.
- Word-model parameters come from the code that defines them (src/cww, experiments/rq2).
- Figures are copied from results/*/figures/ to paper/figures/<part>_<name>.png.

Run from anywhere:  python -I paper/scripts/export_tables.py
"""
from __future__ import annotations

import math
import re
import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from paper.scripts.export_numbers import fmt_num  # noqa: E402

TAB = ROOT / 'paper/generated/tables'
FIG = ROOT / 'paper/figures'
HEADER = '% Generated by paper/scripts/export_tables.py from results/. Do not edit by hand.\n'


def load(part: str) -> pd.DataFrame:
    df = pd.read_csv(ROOT / f'results/{part}/metrics.csv')
    return df.rename(columns={'system': 'group'}).set_index(['metric', 'group', 'stratum'])


M = {p: load(p) for p in ['rq1', 'rq2', 'counselbench', 'demo']}


def row(part, metric, group, stratum='overall'):
    return M[part].loc[(metric, group, stratum)]


def est(part, metric, group, stratum='overall') -> str:
    r = row(part, metric, group, stratum)
    if math.isnan(r.estimate):
        return 'n/a'
    if math.isnan(r.ci_lo) and float(r.estimate).is_integer():
        return str(int(r.estimate))
    return fmt_num(r.estimate)


def ci(part, metric, group, stratum='overall') -> str:
    r = row(part, metric, group, stratum)
    if math.isnan(r.ci_lo):
        return ''
    return f'[{fmt_num(r.ci_lo)}, {fmt_num(r.ci_hi)}]'


def full(part, metric, group, stratum='overall') -> str:
    c = ci(part, metric, group, stratum)
    return est(part, metric, group, stratum) + (f' {c}' if c else '')


def tex_escape(s: str) -> str:
    return s.replace('&', r'\&').replace('%', r'\%').replace('_', r'\_').replace('#', r'\#')


def write(name: str, body: str) -> None:
    (TAB / f'{name}.tex').write_text(HEADER + body, encoding='utf-8')


def tabular(colspec: str, head: list[str], rows: list[list[str]], small=True) -> str:
    lines = [r'\begingroup' + (r'\footnotesize' if small else ''), rf'\begin{{tabular}}{{{colspec}}}', r'\toprule',
             ' & '.join(head) + r' \\', r'\midrule']
    for r in rows:
        lines.append(r'\midrule' if r == ['MIDRULE'] else ' & '.join(r) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\endgroup', '']
    return '\n'.join(lines)


def est_ci_rows(label: str, cells: list[tuple]) -> list[list[str]]:
    """Two rows per entity: estimates, then CIs in a smaller font."""
    return [[label] + [est(*c) for c in cells],
            [''] + [r'{\scriptsize ' + ci(*c) + '}' for c in cells]]

